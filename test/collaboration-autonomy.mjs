import assert from 'node:assert/strict'
import { setTimeout as delay } from 'node:timers/promises'
import { latestPrompt, tool, withCollaborationHost } from './collaboration-host.mjs'

const [dsh, archive] = process.argv.slice(2)
assert(dsh && archive)
const owner = 'synthetic-autonomy-owner'
const worker = 'synthetic-autonomy-worker'
const third = 'synthetic-autonomy-third'
const fourth = 'synthetic-autonomy-fourth'
const initial = '你问一下00-main做了那些事情'
const initialGoal = '做了那些事情'
const second = '你问一下00-main今早检查了什么'
const secondGoal = '今早检查了什么'
const blocked = initial + '并把结果发给03窗口'
const nativeStart = '给01-session-bridge这个窗口问它今天天气怎么样'
const weather = '今天天气怎么样'
const progress = '发现合成记录，请问需不需要核对第二个文件？'
const firstAnswer = '合成记录已逐项对照。\n  第二行保留缩进。\n'
const followup = '请继续核对第二个合成文件。'
const followupAnswer = '第二个合成文件的指纹一致。'
const secondAnswer = '今早只读核对了合成清单。'
const weatherAnswer = '合成天气记录为多云。'
const ignored = '不能投递给未授权窗口。'
const naturalBody = '请把合成进展返回原主控。'
const naturalAnswer = '通过同一甲审任务返回的合成进展。'
const marker = /^DSH-WORKFLOW TASK ([a-f0-9-]+)$/
const exchange = /^任务消息 · ([a-zA-Z0-9_-]+) · ([a-zA-Z0-9_-]+) → ([a-zA-Z0-9_-]+)\n\n([\s\S]+)$/u
const planned = new Map()
const formalText = '合成正式核验已完成当前检查，等待正式回报。'
const formalFinish = '请提交合成正式回报。'
let formalClaim
let formalPhase
const bodyOf = ({ content }) => exchange.exec(content?.[0]?.text)?.[4]
const send = (to, request_id, text) => tool('send_session_message', { to, request_id, text })
const natural = (draft) => tool('send_natural_session_message', { draft })
const noticeText = '[model changed: assistant turns above this point were generated by synthetic-before; the session continues with synthetic-after]'

function decide({ messages }) {
  const match = latestPrompt(messages, (text) =>
    [initial, second, blocked, nativeStart, initialGoal, secondGoal, weather].includes(text) ||
    planned.has(text) || marker.test(text) || exchange.test(text))
  if (!match) return { reply: '合成窗口正常结束。' }
  const { text, results } = match
  if (planned.has(text)) return planned.get(text)(results)
  if (text === initial) {
    if (results.length === 0) return send(worker, 'wrong-tool-on-first-query', '模型生成的正文不得覆盖原问句')
    if (results.length === 1) return tool('send_natural_session_message')
    assert.deepEqual(results, [{ state: 'waiting_for_owner_turn_end' }, { state: 'waiting_for_owner_turn_end' }])
    return { reply: '等待宿主派工。' }
  }
  if (text === blocked) {
    if (results.length === 0) return tool('workflow_delegate_direct')
    assert.equal(results[0].error, 'workflow_direct_owner_request_required')
  }
  if (text === initialGoal) {
    if (results.length === 0) return send(owner, 'initial-progress', progress)
    if (results.length === 1) return natural(progress)
    assert.equal(results[0].delivery, 'queued')
    assert.equal(results[1].duplicate, true)
    assert.equal(results[1].messageId, results[0].messageId)
    return { reply: firstAnswer }
  }
  if (text === secondGoal) return { reply: secondAnswer }
  if (text === weather) return { reply: weatherAnswer }
  if (formalPhase && marker.test(text)) {
    if (formalPhase === 'unclaimed') return { reply: ignored }
    if (!results.length) return tool('workflow_claim', { id: marker.exec(text)[1] })
    formalClaim ??= results[0]
    return { reply: formalText }
  }
  if (exchange.test(text)) {
    const [, , from, , body] = exchange.exec(text)
    if (from === owner && body === followup) {
      if (results.length === 0) return natural(followupAnswer)
      assert.equal(results[0].delivery, 'queued')
      return { reply: followupAnswer }
    }
    if (from === owner && body === naturalBody) return { reply: naturalAnswer }
    if (from === owner && body === formalFinish) {
      if (!results.length) return tool('workflow_report', { id: formalClaim.id, token: formalClaim.token,
        attempt: formalClaim.attempt, status: 'completed', summary: '合成正式成果。', evidence: ['synthetic-formal'] })
      assert.equal(results[0].queued, true)
      return { reply: '正式回报已提交。' }
    }
  }
  return { reply: '合成窗口正常结束。' }
}

await withCollaborationHost({ dsh, archive, decide, timeRefreshIntervalMs: 0 }, async (host) => {
  await host.createSessions([[owner, '01-session-bridge'], [worker, '00-main'],
    [third, '03-合成备用'], [fourth, '04-合成核查']])
  await host.save({ enabled: false, workflowEnabled: true, allowedSessions: [owner, worker, third, fourth] })

  const read = async (id) => {
    try {
      const { records } = await host.rpc('session/events', {
        request: { address: { kind: 'session', sessionId: id }, maxMessages: 300 },
      })
      return records.map(({ event }) => event).filter(Boolean)
    } catch (error) {
      if (!String(error.message).includes('session/agent-busy')) throw error
      return []
    }
  }
  const inputs = async (id, kind) => (await read(id)).filter(({ type, data }) =>
    type === 'user/message' && data.source?.bridgeWorkflowKind === kind)
  const messages = async (id, body) => (await inputs(id, 'conversation')).filter(({ data }) => bodyOf(data) === body)
  const receive = (id, body) => host.until(async () => (await messages(id, body))[0], 'native task delivery of ' + body)
  const call = async (id, text, call) => {
    planned.set(text, (results) => results.length ? undefined : call)
    try { return (await host.prompt(id, text)).results[0] } finally { planned.delete(text) }
  }

  await host.prompt(owner, blocked)
  assert.equal((await inputs(worker, 'task')).length, 0)
  await host.rename(worker, '合成审核')
  await host.prompt(owner, '你问一下合成审核备用窗口多大内存够用')
  assert.equal((await inputs(worker, 'task')).length, 0)
  await host.rename(worker, '00-main')
  await host.rename(third, '00-main备用')
  await host.save({ allowedSessions: [owner, worker] })
  await host.prompt(owner, '你问一下00-main备用窗口多大内存够用')
  assert.equal((await inputs(worker, 'task')).length, 0)
  assert.equal((await inputs(third, 'task')).length, 0)
  await host.rename(third, '03-合成备用')
  await host.save({ allowedSessions: [owner, worker, third, fourth] })
  await host.idle(owner)
  const switched = await host.rpc('session/selectModel', {
    request: { sessionId: owner, provider: 'deepseek-official', model: 'deepseek-v4-pro' },
  })
  assert.equal(switched.selected.model, 'deepseek-v4-pro')
  const source = await host.prompt(owner, initial)
  assert(source.records.some(({ type, data }) => type === 'user/message' &&
    data.source?.kind === 'model-selection' && data.source.form === 'notice'))
  const first = await receive(owner, firstAnswer)
  assert.equal(first.data.source.senderSessionId, worker)
  const initialTask = first.data.source.bridgeWorkflowTask
  const initialJob = first.data.source.bridgeWorkflowId
  assert.equal((await messages(owner, progress)).length, 1)
  assert.equal((await messages(owner, firstAnswer)).length, 1)
  const assigned = (await inputs(worker, 'task')).find(({ data }) => data.source.bridgeWorkflowId === initialJob)
  assert(assigned.data.content.some(({ text }) => text === initialGoal))
  assert(!(await inputs(worker, 'task')).some(({ data }) =>
    data.content.some(({ text }) => text.includes('模型生成的正文不得覆盖'))))

  await host.prompt(owner, '让「03-合成备用」窗口核对合成附加任务。')
  const otherTask = await host.until(async () => (await inputs(third, 'task'))[0], 'second active recipient')
  await host.idle(third)
  await host.idle(owner)
  const otherJob = otherTask.data.source.bridgeWorkflowId
  const wrongTarget = await call(owner, '请给00-main窗口发消息', send(third, 'wrong-peer', ignored))
  assert.equal(wrongTarget.error, 'workflow_task_mismatch')
  const vague = await call(owner, '给他继续补一个点', send(third, 'vague-peer', ignored))
  assert.equal(vague.error, 'workflow_task_reference_required')
  assert.deepEqual(new Set(vague.tasks.map(({ job }) => job)), new Set([initialJob, otherJob]))
  const wrongReference = await call(owner, '给当前任务补充 ' + initialTask, send(third, 'wrong-reference', ignored))
  assert.equal(wrongReference.error, 'workflow_task_mismatch')
  const conflictingSources = await call(owner, '请给00-main窗口发消息：提到任务 ' +
    otherTask.data.source.bridgeWorkflowTask, send(worker, 'conflicting-constraints',
    '提到任务 ' + otherTask.data.source.bridgeWorkflowTask))
  assert.equal(conflictingSources.error, 'workflow_task_mismatch')
  const ordinaryBody = '合成补充只送给主控点名的执行窗。'
  const exactPrompt = '请给00-main窗口发消息：' + ordinaryBody
  const changedBody = await call(owner, exactPrompt, send(worker, 'changed-body', ignored))
  assert.equal(changedBody.error, 'owner_text_cannot_be_replaced')
  const correct = await call(owner, exactPrompt, send(worker, 'correct-peer', ordinaryBody))
  assert.equal(correct.job, initialJob)
  await receive(worker, ordinaryBody)
  const naturalPrompt = '请给00-main窗口发消息：' + naturalBody
  const overridden = await call(owner, naturalPrompt, natural(ignored))
  assert.equal(overridden.error, 'owner_text_cannot_be_replaced')
  planned.set(naturalPrompt, (results) => {
    if (!results.length) return tool('send_natural_session_message')
    if (results.length === 1) return send(worker, 'cross-tool-repeat', naturalBody)
  })
  const throughNatural = await host.prompt(owner, naturalPrompt)
  planned.delete(naturalPrompt)
  assert.equal(throughNatural.results[0].job, initialJob, JSON.stringify(throughNatural.results))
  assert.equal(throughNatural.results[1].duplicate, true)
  assert.equal(throughNatural.results[1].messageId, throughNatural.results[0].messageId)
  const returned = await receive(owner, naturalAnswer)
  assert.equal(returned.data.source.bridgeWorkflowId, initialJob)
  assert.equal((await messages(worker, naturalBody)).length, 1)
  assert.equal((await messages(owner, naturalAnswer)).length, 1)

  await host.rename(worker, '02-合成甲审')
  const aliasBody = '工作区短号选择合成甲审任务。'
  const viaAlias = await call(owner, '给02窗口发消息：' + aliasBody, tool('send_natural_session_message'))
  assert.equal(viaAlias.job, initialJob)
  await receive(worker, aliasBody)
  await host.rename(third, '02-合成备选')
  const ambiguousAlias = await call(owner, '给02窗口发消息：' + ignored, tool('send_natural_session_message'))
  assert.equal(ambiguousAlias.error, 'workflow_task_target_required')
  assert.equal((await messages(worker, ignored)).length, 0)
  assert.equal((await messages(third, ignored)).length, 0)
  await host.rename(third, '03-合成备用')
  await host.rename(worker, '00-main')

  const queuedBody = '核对送达前的宿主标题变更。'
  const queuedPrompt = '请给00-main窗口发消息：' + queuedBody
  let reservation
  let release = false
  planned.set(queuedPrompt, async (results) => {
    if (!results.length) return send(worker, 'renamed-before-delivery', queuedBody)
    reservation = results[0]
    while (!release) await delay(20)
  })
  const queued = await host.submit(owner, queuedPrompt)
  await host.until(() => reservation?.delivery === 'queued', 'title-bound message reserved')
  await host.rename(worker, '00-main-已改名')
  await host.rename(third, '00-main')
  release = true
  await host.turn(owner, queued)
  planned.delete(queuedPrompt)
  const dropped = await host.until(async () => {
    const receipt = await call(owner, '查看改名时的投递状态', tool('session_message_status', {
      job: initialJob, request_id: 'renamed-before-delivery',
    }))
    return receipt?.delivery === 'not_delivered' && receipt
  }, 'the original reservation settles without delivery after the rename')
  assert.equal(dropped.messageId, reservation.messageId)
  assert.equal(dropped.delivery, 'not_delivered')
  assert.equal((await messages(worker, queuedBody)).length, 0)
  assert.equal((await messages(third, queuedBody)).length, 0)
  assert.equal((await messages(third, ignored)).length, 0)
  await host.rename(third, '03-合成备用')
  await host.rename(worker, '00-main')
  await host.prompt(owner, '取消委托 ' + otherTask.data.source.bridgeWorkflowTask)
  await host.save({ enabled: true })
  const unrelated = await call(owner, '给03-合成备用窗口发消息：这是一条独立的合成消息。', tool('send_natural_session_message'))
  assert.equal(unrelated.delivery, 'delivered')
  assert.equal(unrelated.to, third)
  assert.equal(unrelated.job, undefined)
  assert.equal((await inputs(third, 'conversation')).length, 0)
  await host.save({ enabled: false })
  console.log('PASS native owner selects the target, both tools share one task route, unrelated ordinary send remains available, and renamed targets do not receive')

  await host.prompt(owner, second)
  const independent = await receive(owner, secondAnswer)
  assert.notEqual(independent.data.source.bridgeWorkflowId, initialJob)
  assert.equal((await call(owner, '给执行窗补充。', natural(ignored))).error, 'workflow_task_reference_required')
  assert.equal((await call(worker, '给主控回报 ' + initialTask, natural(ignored))).error, 'bridge_disabled')
  assert.equal((await call(owner, '给其他窗补充 ' + initialTask, send(third, 'outside', ignored))).error,
    'workflow_task_mismatch')
  const delivered = await call(owner, '补充任务 ' + initialTask, natural(followup))
  assert.equal(delivered.job, initialJob)
  const followupResult = await receive(owner, followupAnswer)
  assert.equal(followupResult.data.source.bridgeWorkflowId, initialJob)
  await host.idle(owner)
  assert.equal((await messages(owner, followupAnswer)).length, 1)
  assert.equal((await inputs(third, 'conversation')).length, 0)
  assert.equal((await messages(owner, ignored)).length, 0)

  // The same-looking text as a real model notice is an ordinary native input.
  await host.prompt(owner, noticeText)
  assert.equal((await inputs(worker, 'task')).length, 2)
  const result = await host.prompt(worker, nativeStart)
  assert.deepEqual(result.results, [])
  const nativeAnswer = await receive(worker, weatherAnswer)
  assert.equal(nativeAnswer.data.source.senderSessionId, owner)
  assert.equal((await messages(worker, weatherAnswer)).length, 1)

  await host.prompt(owner, '取消委托 ' + initialTask)
  const denied = await call(owner, '继续已撤回任务 ' + initialTask, natural(ignored))
  assert(denied.error)
  await host.stop()
  await host.start()
  await delay(1200)
  assert.equal((await messages(owner, firstAnswer)).length, 1)
  assert.equal((await messages(owner, followupAnswer)).length, 1)
  console.log('PASS catalog title and exact owner question, native model notice, two legacy tools, automatic plain replies, task isolation, third-window denial, withdrawal and restart')

  const formalTask = 'synthetic-formal-autonomy'
  const proposal = {
    task: formalTask, goal: '完成合成正式核验。', ttlMinutes: 10, budget: 3, conversation: true,
    scopes: [{ name: 'verify', windows: ['00-main', '03-合成备用', '04-合成核查'], purpose: '只读核对合成文件' }],
  }
  const proposalText = '请拟定一项有两窗往返的合成正式核验。'
  planned.set(proposalText, (results) => results.length ? { reply: results[0].preview } : tool('workflow_propose', proposal))
  const preview = await host.prompt(owner, proposalText)
  planned.delete(proposalText)
  assert(preview.results[0].preview)
  const assignment = (item, target) => ({ task: formalTask, item, target, scope: 'verify', attempt: 1,
    instructions: '核对合成文件。', acceptance: '提交合成正式回报及证据。' })
  formalPhase = 'unclaimed'
  planned.set('确认委托', (results) => {
    if (!results.length) return tool('workflow_confirm')
    if (results.length === 1) return tool('workflow_dispatch', assignment('unclaimed', third))
  })
  await host.prompt(owner, '确认委托')
  planned.delete('确认委托')
  const getJob = (item) => host.snapshot(owner, formalTask).jobs.find((job) => job.item === item)
  const unclaimed = await host.until(() => {
    const job = getJob('unclaimed')
    return job?.wake.state === 'uncertain' && job
  }, 'formal job without a claim remains uncertain')
  assert.equal(unclaimed.claim, undefined)
  assert.equal((await messages(owner, ignored)).length, 0)

  formalPhase = 'claimed'
  const resumed = '继续委托 ' + formalTask
  const reserved = await call(owner, resumed, tool('workflow_dispatch', assignment('claimed', worker)))
  const interim = await receive(owner, formalText)
  assert.equal(interim.data.source.bridgeWorkflowId, reserved.id)
  assert.equal(getJob('claimed').wake.state, 'claimed')
  assert.equal(getJob('claimed').report, undefined)
  const another = await call(owner, resumed, tool('workflow_dispatch', assignment('claimed-other', fourth)))
  await host.until(() => getJob('claimed-other')?.wake.state === 'claimed', 'another worker claims the same task')
  await host.idle(fourth)
  await host.idle(owner)
  const additional = '请给这个任务里的另一执行窗核对合成资料。'
  const chosen = await call(owner, '补充已授权的任务 ' + formalTask, send(fourth, 'same-grant-worker', additional))
  assert.equal(chosen.job, another.id)
  await receive(fourth, additional)
  const request = await call(owner, resumed, send(worker, 'same-grant-finish', formalFinish))
  assert.equal(request.job, reserved.id)
  await host.until(() => getJob('claimed').report?.status === 'completed', 'formal terminal report')
  assert.deepEqual(getJob('claimed').report.evidence, ['synthetic-formal'])
  console.log('PASS a bound formal task can choose either approved worker; explicit claims and terminal reports remain required')
})
